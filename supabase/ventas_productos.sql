create table if not exists public.ventas_productos (
  id              bigint generated by default as identity primary key,
  producto_id     text,                      -- id del producto (texto: sirve sea número o uuid)
  producto_nombre text    not null,          -- se guarda el nombre por si luego se borra el producto
  cantidad        integer not null default 1 check (cantidad > 0),
  precio_unitario integer not null check (precio_unitario >= 0),
  total           integer not null check (total >= 0),
  fecha           date    not null default (now() at time zone 'America/Costa_Rica')::date,
  created_at      timestamptz not null default now()
);

create index if not exists ventas_productos_fecha_idx on public.ventas_productos (fecha);

-- Seguridad: solo el barbero con sesión iniciada puede ver y registrar ventas.
alter table public.ventas_productos enable row level security;

drop policy if exists "ventas: solo autenticados" on public.ventas_productos;
create policy "ventas: solo autenticados"
  on public.ventas_productos
  for all
  to authenticated
  using (true)
  with check (true);
